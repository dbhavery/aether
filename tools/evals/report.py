"""Markdown report renderer for the eval runner.

One section per scenario with status, expectations table, and the
response body. Keeps the format diff-friendly so a baseline report
can be committed alongside the handoff and future runs surface
clear deltas.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from __main__ import ScenarioResult  # pragma: no cover


def build_markdown_report(results) -> str:
    passed = sum(1 for r in results if r.status == "pass")
    failed = sum(1 for r in results if r.status == "fail")
    skipped = sum(1 for r in results if r.status == "skip")

    lines: list[str] = []
    lines.append("# Aether eval run — v1 scaffold")
    lines.append("")
    lines.append(f"- **Pass:** {passed}")
    lines.append(f"- **Fail:** {failed}")
    lines.append(f"- **Skip:** {skipped}")
    lines.append(f"- **Total:** {len(results)}")
    lines.append("")

    # Group by domain for readability.
    by_domain: dict[str, list] = {}
    for r in results:
        by_domain.setdefault(r.scenario.domain, []).append(r)

    for domain in sorted(by_domain):
        lines.append(f"## {domain}")
        lines.append("")
        for r in by_domain[domain]:
            badge = {"pass": "✅", "fail": "❌", "skip": "⊘"}.get(r.status, "?")
            lines.append(f"### {badge} `{r.scenario.id}`")
            lines.append("")
            if r.note:
                lines.append(f"> {r.note}")
                lines.append("")
            if r.response:
                lines.append("**Response:**")
                lines.append("")
                lines.append("```")
                lines.append(r.response)
                lines.append("```")
                lines.append("")
            if r.expectations:
                lines.append("| Kind | Status | Detail |")
                lines.append("| --- | --- | --- |")
                for er in r.expectations:
                    detail = er.detail.replace("|", "\\|") if er.detail else ""
                    lines.append(f"| {er.kind} | {er.status} | {detail} |")
                lines.append("")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "Generated by `tools/evals/__main__.py`. See "
        "`docs/QUALITY-EVAL-V1-ARCHITECTURE.md` for the design."
    )
    lines.append("")
    return "\n".join(lines)
